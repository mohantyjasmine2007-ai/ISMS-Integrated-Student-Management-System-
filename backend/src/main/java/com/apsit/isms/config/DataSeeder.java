package com.apsit.isms.config;

import com.apsit.isms.repository.CourseRepository;
import com.apsit.isms.repository.StudentRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;

@Component
public class DataSeeder implements CommandLineRunner {

    @Autowired
    private StudentRepository studentRepository;

    @Autowired
    private CourseRepository courseRepository;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Override
    public void run(String... args) throws Exception {
        long studentCount = studentRepository.count();
        long courseCount = courseRepository.count();

        if (studentCount > 0 && courseCount > 0) {
            System.out.println(" [DATABASE SEED] Database already populated with " + studentCount + " students and " + courseCount + " courses.");
            return;
        }

        System.out.println(" [DATABASE SEED] Populating database with official SE IT Div B records from database_setup.sql...");

        ClassPathResource resource = new ClassPathResource("database_setup.sql");
        if (!resource.exists()) {
            System.err.println(" [DATABASE SEED ERROR] database_setup.sql not found on classpath.");
            return;
        }

        int executedCount = 0;
        int errorCount = 0;

        try (BufferedReader reader = new BufferedReader(new InputStreamReader(resource.getInputStream(), StandardCharsets.UTF_8))) {
            StringBuilder sb = new StringBuilder();
            String line;

            while ((line = reader.readLine()) != null) {
                line = line.trim();
                if (line.isEmpty() || line.startsWith("--") || line.startsWith("/*")) {
                    continue;
                }

                sb.append(line).append(" ");

                if (line.endsWith(";")) {
                    String stmt = sb.toString().trim();
                    sb.setLength(0);

                    // Execute INSERT statements only (tables are already generated by Hibernate/JPA)
                    if (stmt.toUpperCase().startsWith("INSERT INTO")) {
                        try {
                            // Strip trailing semicolon for JDBC drivers
                            if (stmt.endsWith(";")) {
                                stmt = stmt.substring(0, stmt.length() - 1);
                            }
                            jdbcTemplate.execute(stmt);
                            executedCount++;
                        } catch (Exception ex) {
                            errorCount++;
                            // Ignore duplicates or minor constraint differences
                        }
                    }
                }
            }
        }

        System.out.println(" [DATABASE SEED COMPLETED] Executed " + executedCount + " seed records successfully. (Ignored/Errors: " + errorCount + ")");
        System.out.println(" [DATABASE STATUS] Current Students: " + studentRepository.count() + " | Courses: " + courseRepository.count());
    }
}
